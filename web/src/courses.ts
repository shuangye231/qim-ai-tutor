export const courseById = (courseId: CourseId) => courses.find((course) => course.id === courseId) || courses[0]
export const isCourseId = (value: unknown): value is CourseId => courses.some((course) => course.id === value)
export const stageTopics = (value: CourseStage) => value.modules.flatMap((item) => item.topics)
export const courseTopics = (course: CourseDefinition) => course.stages.flatMap(stageTopics)
export const stageCompletedCount = (value: CourseStage, completed: string[]) => stageTopics(value).filter((topic) => completed.includes(topic.id)).length
export const isStageComplete = (value: CourseStage, completed: string[]) => stageCompletedCount(value, completed) === stageTopics(value).length
export const unlockedStageIndex = (course: CourseDefinition, completed: string[]) => {
  const firstIncomplete = course.stages.findIndex((value) => !isStageComplete(value, completed))
  return firstIncomplete === -1 ? course.stages.length : firstIncomplete
}
