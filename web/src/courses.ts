import type { CourseId } from './types'

export interface CourseTopic { id: string; title: string }
export interface CourseModule { id: string; title: string; topics: CourseTopic[] }
export interface CourseStage { id: string; title: string; summary: string; modules: CourseModule[] }
export interface CourseDefinition { id: CourseId; name: string; shortName: string; description: string; stages: CourseStage[] }

const module = (courseId: CourseId, stage: number, moduleIndex: number, title: string, titles: string[]): CourseModule => ({
  id: `${courseId}-${stage}-${moduleIndex}`,
  title,
  topics: titles.map((topicTitle, topicIndex) => ({ id: `${courseId}-${stage}-${moduleIndex}-${topicIndex + 1}`, title: topicTitle })),
})
const stage = (courseId: CourseId, index: number, title: string, summary: string, modules: Array<[string, string[]]>): CourseStage => ({
  id: `${courseId}-stage-${index}`,
  title,
  summary,
  modules: modules.map(([moduleTitle, titles], moduleIndex) => module(courseId, index, moduleIndex + 1, moduleTitle, titles)),
})

